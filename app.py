app = Flask(__name__)
DB_FILE = "local_library.db"
SQL_EXPORT = "schema.sql"
D1_DB_NAME = "my-library-db"

def init_db():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS books (
        id TEXT PRIMARY KEY,
        title TEXT NOT NULL,
        author TEXT NOT NULL,
        cover_url TEXT NOT NULL,
        b2_key TEXT NOT NULL
    );
    """)
    conn.commit()
    conn.close()

def export_to_sql():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM books")
    rows = cursor.fetchall()
    conn.close()

    with open(SQL_EXPORT, "w", encoding="utf-8") as f:
        f.write("-- Auto-generated by Local Python Dashboard\n")
        f.write("DROP TABLE IF EXISTS books;\n\n")
        f.write("CREATE TABLE books (\n")
        f.write("  id TEXT PRIMARY KEY,\n")
        f.write("  title TEXT NOT NULL,\n")
        f.write("  author TEXT NOT NULL,\n")
        f.write("  cover_url TEXT NOT NULL,\n")
        f.write("  b2_key TEXT NOT NULL\n")
        f.write(");\n\n")
        
        for row in rows:
            # Escape single quotes for SQL safety
            clean_title = row[1].replace("'", "''")
            clean_author = row[2].replace("'", "''")
            f.write(f"INSERT INTO books (id, title, author, cover_url, b2_key) VALUES ('{row[0]}', '{clean_title}', '{clean_author}', '{row[3]}', '{row[4]}');\n")

