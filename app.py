@app.route("/")
def index():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM books")
    books = cursor.fetchall()
    conn.close()
    return render_template_string(HTML_TEMPLATE, books=books)

@app.route("/add", methods=["POST"])
def add_book():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute(
        "INSERT OR REPLACE INTO books VALUES (?, ?, ?, ?, ?)",
        (request.form["id"], request.form["title"], request.form["author"], request.form["cover_url"], request.form["b2_key"])
    )
    conn.commit()
    conn.close()
    export_to_sql()
    return redirect(url_for("index"))

@app.route("/delete/<book_id>", methods=["POST"])
def delete_book(book_id):
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("DELETE FROM books WHERE id = ?", (book_id,))
    conn.commit()
    conn.close()
    export_to_sql()
    return redirect(url_for("index"))

@app.route("/sync", methods=["POST"])
def sync_cloudflare():
    export_to_sql()
    cmd = f"npx wrangler d1 execute {D1_DB_NAME} --remote --file=./{SQL_EXPORT}"
    subprocess.run(cmd, shell=True)
    return redirect(url_for("index"))

